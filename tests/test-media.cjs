const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '../home/.config/omarchy/plugins');
const timeline = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'xmilon.media/Timeline.js'), 'utf8'), timeline);
assert.equal(timeline.timeLabel(65), '1:05');
assert.equal(timeline.timeLabel(NaN), '0:00');
assert.equal(timeline.seekTarget(-10, 240), 0);
assert.equal(timeline.seekTarget(999, 240), 240);
assert.equal(timeline.seekTarget(Infinity, 240), 0);
assert.equal(timeline.tooltip('<img src="https://example.invalid"> & music'), '&lt;img src="https://example.invalid"&gt; &amp; music');
const error = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'quickshell.spotify/SessionError.js'), 'utf8'), error);
assert.match(error.message('librespot does not support "free" accounts.'), /Free.*Premium/);
assert.match(error.message('Spotify Premium is required'), /Premium/);
assert.match(error.message('unrelated error with secret'), /reconnect/);
assert.equal(error.message('unrelated error with secret').includes('secret'), false);
console.log('Media seeking, markup, and Spotify error checks passed.');
